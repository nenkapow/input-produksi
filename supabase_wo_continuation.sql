-- Run as a trusted owner after all previous WO migrations, in one transaction.
BEGIN;
CREATE TABLE IF NOT EXISTS public.production_wo_continuations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 parent_wo_ref text NOT NULL, child_wo_ref text NOT NULL UNIQUE,
 added_qty numeric NOT NULL CHECK (added_qty > 0), carryover_qty numeric NOT NULL CHECK (carryover_qty >= 0 AND carryover_qty <= added_qty),
 effective_date date NOT NULL, effective_shift smallint NOT NULL CHECK (effective_shift BETWEEN 1 AND 3),
 note text, parent_target numeric NOT NULL, parent_actual numeric NOT NULL, parent_excess numeric NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS wo_continuation_child_ref_idx ON public.production_wo_continuations (public.wo_normalize(child_wo_ref));
CREATE UNIQUE INDEX IF NOT EXISTS wo_continuation_parent_ref_idx ON public.production_wo_continuations (public.wo_normalize(parent_wo_ref));

-- A normalized reference has exactly one immutable target. Start fields preserve
-- metadata even when legacy logs are subsequently removed.
CREATE TABLE IF NOT EXISTS public.production_wo_targets (
 wo_ref text PRIMARY KEY, target_qty numeric NOT NULL CHECK (target_qty > 0),
 start_date date, start_shift integer, created_at timestamptz NOT NULL DEFAULT now(),
 source text NOT NULL, locked_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS wo_targets_normalized_ref_idx ON public.production_wo_targets (public.wo_normalize(wo_ref));

-- Stop rather than choosing between conflicting target snapshots.
DO $$
DECLARE conflict_ref text;
BEGIN
 SELECT min(l.wo_ref) INTO conflict_ref FROM public.logs l
 WHERE public.wo_normalize(l.wo_ref) <> '' AND l.wo_qty IS NOT NULL AND l.wo_qty > 0
 GROUP BY public.wo_normalize(l.wo_ref) HAVING count(DISTINCT l.wo_qty) > 1 LIMIT 1;
 IF conflict_ref IS NOT NULL THEN RAISE EXCEPTION 'Konflik target WO %, periksa logs.wo_qty sebelum migrasi', conflict_ref; END IF;
 IF EXISTS (SELECT 1 FROM public.production_wo_targets t JOIN public.logs l ON public.wo_normalize(t.wo_ref)=public.wo_normalize(l.wo_ref) WHERE l.wo_qty > 0 AND l.wo_qty <> t.target_qty) THEN RAISE EXCEPTION 'Target tersimpan berbeda dari logs.wo_qty'; END IF;
 IF EXISTS (SELECT 1 FROM public.production_wo_continuations c JOIN public.logs l ON public.wo_normalize(c.child_wo_ref)=public.wo_normalize(l.wo_ref) WHERE l.wo_qty > 0 AND l.wo_qty <> c.added_qty) THEN RAISE EXCEPTION 'Target child berbeda dari logs.wo_qty'; END IF;
END $$;

INSERT INTO public.production_wo_targets (wo_ref,target_qty,start_date,start_shift,source)
SELECT c.child_wo_ref,c.added_qty,c.effective_date,c.effective_shift,'continuation'
FROM public.production_wo_continuations c
ON CONFLICT ((public.wo_normalize(wo_ref))) DO NOTHING;
INSERT INTO public.production_wo_targets (wo_ref,target_qty,start_date,start_shift,source)
SELECT DISTINCT ON (public.wo_normalize(l.wo_ref)) l.wo_ref,l.wo_qty,l.wo_start_date::date,l.wo_start_shift::integer,'legacy_logs'
FROM public.logs l
WHERE public.wo_normalize(l.wo_ref) <> '' AND l.wo_qty > 0 AND l.wo_start_date IS NOT NULL
ORDER BY public.wo_normalize(l.wo_ref),l.tanggal DESC,l.shift DESC,l.id DESC
ON CONFLICT ((public.wo_normalize(wo_ref))) DO NOTHING;
DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM public.production_wo_continuations c JOIN public.production_wo_targets t ON public.wo_normalize(t.wo_ref)=public.wo_normalize(c.child_wo_ref) WHERE t.target_qty<>c.added_qty) THEN RAISE EXCEPTION 'Target child tersimpan berbeda dari continuation'; END IF;
 IF EXISTS (SELECT 1 FROM public.production_wo_assignments a WHERE public.wo_normalize(a.wo_ref)<>'' AND NOT EXISTS (SELECT 1 FROM public.production_wo_targets t WHERE public.wo_normalize(t.wo_ref)=public.wo_normalize(a.wo_ref))) THEN RAISE EXCEPTION 'Assignment WO memiliki target atau tanggal mulai yang belum tersedia di logs'; END IF;
 IF EXISTS (SELECT 1 FROM public.production_wo_status w WHERE public.wo_normalize(w.wo_ref)<>'' AND NOT EXISTS (SELECT 1 FROM public.production_wo_targets t WHERE public.wo_normalize(t.wo_ref)=public.wo_normalize(w.wo_ref))) THEN RAISE EXCEPTION 'Status WO memiliki target atau tanggal mulai yang belum tersedia di logs'; END IF;
END $$;

-- Narrow readers expose WO metadata while log queries remain SECURITY INVOKER.
CREATE OR REPLACE FUNCTION public.wo_targets_read()
RETURNS TABLE (wo_ref text,target_qty numeric,start_date date,start_shift integer)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
 SELECT t.wo_ref,t.target_qty,t.start_date,t.start_shift FROM public.production_wo_targets t
$$;
CREATE OR REPLACE FUNCTION public.wo_continuation_read(p_ref text)
RETURNS TABLE (parent_wo_ref text,child_wo_ref text,carryover_qty numeric)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
 SELECT c.parent_wo_ref,c.child_wo_ref,c.carryover_qty FROM public.production_wo_continuations c
 WHERE public.wo_normalize(c.parent_wo_ref)=public.wo_normalize(p_ref) OR public.wo_normalize(c.child_wo_ref)=public.wo_normalize(p_ref)
$$;
CREATE OR REPLACE FUNCTION public.wo_metadata(p_ref text)
RETURNS TABLE (wo_ref text, wo_qty numeric, wo_start_date date, wo_start_shift integer)
LANGUAGE sql STABLE SECURITY INVOKER AS $$
 SELECT t.wo_ref,t.target_qty,t.start_date,t.start_shift FROM public.wo_targets_read() t WHERE public.wo_normalize(t.wo_ref)=public.wo_normalize(p_ref)
 UNION ALL
 (SELECT l.wo_ref::text,l.wo_qty::numeric,l.wo_start_date::date,l.wo_start_shift::integer FROM public.logs l
 WHERE public.wo_normalize(l.wo_ref)=public.wo_normalize(p_ref) AND l.wo_qty>0 AND l.wo_start_date IS NOT NULL
 AND NOT EXISTS (SELECT 1 FROM public.wo_targets_read() t WHERE public.wo_normalize(t.wo_ref)=public.wo_normalize(p_ref))
 ORDER BY l.tanggal DESC,l.shift DESC,l.id DESC LIMIT 1)
$$;
CREATE OR REPLACE FUNCTION public.wo_list_metadata()
RETURNS TABLE (wo_ref text, wo_qty numeric, wo_start_date date, wo_start_shift integer)
LANGUAGE sql STABLE SECURITY INVOKER AS $$
 SELECT t.wo_ref,t.target_qty,t.start_date,t.start_shift FROM public.wo_targets_read() t
 UNION ALL
 (SELECT DISTINCT ON (public.wo_normalize(l.wo_ref)) l.wo_ref::text,l.wo_qty::numeric,l.wo_start_date::date,l.wo_start_shift::integer FROM public.logs l
 WHERE public.wo_normalize(l.wo_ref)<>'' AND l.wo_qty>0 AND l.wo_start_date IS NOT NULL
 AND NOT EXISTS (SELECT 1 FROM public.wo_targets_read() t WHERE public.wo_normalize(t.wo_ref)=public.wo_normalize(l.wo_ref))
 ORDER BY public.wo_normalize(l.wo_ref),l.tanggal DESC,l.shift DESC,l.id DESC)
$$;
CREATE OR REPLACE FUNCTION public.wo_progress(p_ref text, p_exclude_id text DEFAULT NULL, p_draft jsonb DEFAULT NULL, p_transfer_id bigint DEFAULT NULL)
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER AS $$
 WITH assignment AS (
   SELECT a.line_code, a.product_code, a.product_name, a.effective_date, a.effective_shift,
     CASE WHEN a.id = p_transfer_id AND p_draft IS NOT NULL THEN
       CASE WHEN (p_draft->>'effective_shift')::integer = 1 THEN (p_draft->>'effective_date')::date - 1 ELSE (p_draft->>'effective_date')::date END
       ELSE a.ended_date END AS ended_date,
     CASE WHEN a.id = p_transfer_id AND p_draft IS NOT NULL THEN
       CASE WHEN (p_draft->>'effective_shift')::integer = 1 THEN 3 ELSE (p_draft->>'effective_shift')::integer - 1 END
       ELSE a.ended_shift END AS ended_shift
   FROM public.production_wo_assignments a WHERE public.wo_normalize(a.wo_ref) = public.wo_normalize(p_ref)
   UNION ALL
   SELECT p_draft->>'line_code', p_draft->>'product_code', p_draft->>'product_name',
     (p_draft->>'effective_date')::date, (p_draft->>'effective_shift')::integer, NULL::date, NULL::integer
   WHERE p_draft IS NOT NULL
 ), matched AS (
   SELECT l.line, l.kode, l.nama, l.okpcs, l.wo_ref
   FROM public.logs l
   WHERE (p_exclude_id IS NULL OR l.id::text <> p_exclude_id)
     AND (public.wo_normalize(l.wo_ref) = public.wo_normalize(p_ref) OR (public.wo_normalize(l.wo_ref) = '' AND NOT EXISTS (SELECT 1 FROM public.wo_continuation_read(p_ref) c WHERE public.wo_normalize(c.child_wo_ref) = public.wo_normalize(p_ref))))
     AND EXISTS (SELECT 1 FROM assignment a
       WHERE public.wo_normalize(l.line) = public.wo_normalize(a.line_code)
         AND public.wo_normalize(l.kode) = public.wo_normalize(a.product_code)
         AND public.wo_normalize(l.nama) = public.wo_normalize(a.product_name)
         AND (l.tanggal::date, l.shift::integer) >= (a.effective_date, a.effective_shift)
         AND (a.ended_date IS NULL OR (l.tanggal::date, l.shift::integer) <= (a.ended_date, a.ended_shift)))
 ), grouped AS (
   SELECT line, kode, nama, sum(coalesce(okpcs,0)) AS ok FROM matched GROUP BY line,kode,nama
 )
 SELECT jsonb_build_object('historical_ok', coalesce((SELECT sum(coalesce(okpcs,0)) FROM matched),0),
   'includes_unreferenced', coalesce((SELECT bool_or(public.wo_normalize(wo_ref) = '') FROM matched),false),
   'is_continuation', EXISTS (SELECT 1 FROM public.wo_continuation_read(p_ref) WHERE public.wo_normalize(child_wo_ref)=public.wo_normalize(p_ref)),
   'production_ok', coalesce((SELECT sum(coalesce(okpcs,0)) FROM matched),0),
   'carryover_qty', coalesce((SELECT carryover_qty FROM public.wo_continuation_read(p_ref) WHERE public.wo_normalize(child_wo_ref)=public.wo_normalize(p_ref)),0),
   'total_progress', coalesce((SELECT sum(coalesce(okpcs,0)) FROM matched),0) + coalesce((SELECT carryover_qty FROM public.wo_continuation_read(p_ref) WHERE public.wo_normalize(child_wo_ref)=public.wo_normalize(p_ref)),0),
   'remaining', (SELECT wo_qty FROM public.wo_metadata(p_ref)) - coalesce((SELECT sum(coalesce(okpcs,0)) FROM matched),0) - coalesce((SELECT carryover_qty FROM public.wo_continuation_read(p_ref) WHERE public.wo_normalize(child_wo_ref)=public.wo_normalize(p_ref)),0),
   'contributions', coalesce((SELECT jsonb_agg(jsonb_build_object('line',line,'kode',kode,'nama',nama,'ok',ok)) FROM grouped),'[]'::jsonb))
$$;


-- Each parent can have one child; subsequent additions continue from that child.
CREATE OR REPLACE FUNCTION public.wo_create_continuation(p_parent text,p_added_qty numeric,p_date date,p_shift integer,p_use_excess boolean,p_assignment_ids bigint[],p_note text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE meta record; a record; parent_actual numeric; excess numeric; carry numeric; child text; prev_date date; prev_shift integer; selected_count integer; info text;
BEGIN
 IF public.wo_normalize(p_parent)='' OR p_added_qty IS NULL OR p_added_qty<=0 OR p_date IS NULL OR p_shift IS NULL OR p_shift NOT BETWEEN 1 AND 3 OR coalesce(cardinality(p_assignment_ids),0)=0 THEN RAISE EXCEPTION 'Data WO lanjutan tidak lengkap'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(public.wo_normalize(p_parent),0));
 -- Prevent a report or assignment from changing between the snapshot and boundary transfer.
 LOCK TABLE public.logs IN SHARE ROW EXCLUSIVE MODE;
 LOCK TABLE public.production_wo_assignments IN SHARE ROW EXCLUSIVE MODE;
 IF public.wo_status_for_ref(p_parent)<>'OPEN' THEN RAISE EXCEPTION 'Parent harus OPEN'; END IF;
 IF EXISTS (SELECT 1 FROM public.production_wo_continuations WHERE public.wo_normalize(parent_wo_ref)=public.wo_normalize(p_parent)) THEN RAISE EXCEPTION 'Parent sudah memiliki WO lanjutan'; END IF;
 SELECT * INTO meta FROM public.wo_metadata(p_parent); IF NOT FOUND OR meta.wo_start_date IS NULL OR meta.wo_start_shift IS NULL THEN RAISE EXCEPTION 'WO parent atau boundary tidak ditemukan'; END IF;
 INSERT INTO public.production_wo_targets (wo_ref,target_qty,start_date,start_shift,source) VALUES(meta.wo_ref,meta.wo_qty,meta.wo_start_date,meta.wo_start_shift,'legacy_fallback') ON CONFLICT ((public.wo_normalize(wo_ref))) DO NOTHING;
 SELECT t.target_qty INTO meta.wo_qty FROM public.production_wo_targets t WHERE public.wo_normalize(t.wo_ref)=public.wo_normalize(p_parent);
 prev_date := CASE WHEN p_shift=1 THEN p_date-1 ELSE p_date END; prev_shift := CASE WHEN p_shift=1 THEN 3 ELSE p_shift-1 END;
 IF (p_date,p_shift)<=(meta.wo_start_date,meta.wo_start_shift) THEN RAISE EXCEPTION 'Boundary child harus setelah awal parent'; END IF;
 SELECT count(*) INTO selected_count FROM public.production_wo_assignments WHERE id=ANY(p_assignment_ids) AND public.wo_normalize(wo_ref)=public.wo_normalize(p_parent) AND ended_date IS NULL;
 IF selected_count <> cardinality(p_assignment_ids) THEN RAISE EXCEPTION 'Assignment tidak valid atau sudah berakhir'; END IF;
 IF EXISTS (SELECT 1 FROM public.production_wo_assignments WHERE public.wo_normalize(wo_ref)=public.wo_normalize(p_parent) AND ((ended_date IS NULL AND (effective_date,effective_shift)>(prev_date,prev_shift)) OR (ended_date IS NOT NULL AND (ended_date,ended_shift)>=(p_date,p_shift)))) THEN RAISE EXCEPTION 'Boundary bertabrakan dengan assignment parent'; END IF;
 IF EXISTS (SELECT 1 FROM public.logs l WHERE (l.tanggal::date,l.shift::integer)>=(p_date,p_shift)
  AND (public.wo_normalize(l.wo_ref)=public.wo_normalize(p_parent) OR (public.wo_normalize(l.wo_ref)='' AND EXISTS (
   SELECT 1 FROM public.production_wo_assignments a WHERE public.wo_normalize(a.wo_ref)=public.wo_normalize(p_parent)
    AND public.wo_normalize(l.line)=public.wo_normalize(a.line_code) AND public.wo_normalize(l.kode)=public.wo_normalize(a.product_code) AND public.wo_normalize(l.nama)=public.wo_normalize(a.product_name)
    AND (l.tanggal::date,l.shift::integer)>=(a.effective_date,a.effective_shift)
    AND (a.ended_date IS NULL OR (l.tanggal::date,l.shift::integer)<=(a.ended_date,a.ended_shift))
  )))) THEN RAISE EXCEPTION 'Sudah ada laporan parent pada atau setelah boundary; pilih boundary setelah laporan tersebut'; END IF;
 parent_actual := (public.wo_progress(p_parent)->>'total_progress')::numeric; excess := greatest(parent_actual-meta.wo_qty,0); carry := CASE WHEN p_use_excess THEN least(excess,p_added_qty) ELSE 0 END;
 child := 'WO-'||to_char(p_date,'YYYYMMDD')||'-'||upper(replace(gen_random_uuid()::text,'-',''));
 IF EXISTS (SELECT 1 FROM public.wo_metadata(child)) OR EXISTS (SELECT 1 FROM public.production_wo_status WHERE public.wo_normalize(wo_ref)=public.wo_normalize(child)) THEN RAISE EXCEPTION 'Referensi child sudah dipakai'; END IF;
 FOR a IN SELECT * FROM public.production_wo_assignments WHERE public.wo_normalize(wo_ref)=public.wo_normalize(p_parent) AND ended_date IS NULL FOR UPDATE LOOP
  IF a.id=ANY(p_assignment_ids) THEN
   UPDATE public.production_wo_assignments SET ended_date=prev_date,ended_shift=prev_shift WHERE id=a.id;
   PERFORM public.create_wo_assignment(child,a.line_code,a.product_code,a.product_name,p_date,p_shift::smallint,NULL);
  ELSE UPDATE public.production_wo_assignments SET ended_date=prev_date,ended_shift=prev_shift WHERE id=a.id; END IF;
 END LOOP;
 INSERT INTO public.production_wo_continuations(parent_wo_ref,child_wo_ref,added_qty,carryover_qty,effective_date,effective_shift,note,parent_target,parent_actual,parent_excess)
 VALUES(meta.wo_ref,child,p_added_qty,carry,p_date,p_shift,p_note,meta.wo_qty,parent_actual,excess);
 INSERT INTO public.production_wo_targets (wo_ref,target_qty,start_date,start_shift,source) VALUES(child,p_added_qty,p_date,p_shift,'continuation');
 INSERT INTO public.production_wo_status(wo_ref,status,closed_reason,note,closed_at,updated_at,remaining_at_close)
 VALUES(meta.wo_ref,'CLOSED','PPIC_ADDITIONAL_WO',p_note,now(),now(),meta.wo_qty-parent_actual)
 ON CONFLICT ((public.wo_normalize(wo_ref))) DO UPDATE SET status='CLOSED',closed_reason='PPIC_ADDITIONAL_WO',note=p_note,closed_at=now(),updated_at=now(),remaining_at_close=meta.wo_qty-parent_actual;
 INSERT INTO public.production_wo_status(wo_ref,status) VALUES(child,'OPEN');
 info := jsonb_build_object('parent_wo_ref',meta.wo_ref,'child_wo_ref',child,'added_qty',p_added_qty,'carryover_qty',carry,'effective_date',p_date,'effective_shift',p_shift,'note',p_note)::text;
 INSERT INTO public.production_wo_actions(wo_ref,action,previous_status,new_status,note) VALUES(meta.wo_ref,'CREATE_CONTINUATION','OPEN','CLOSED',info),(child,'CREATED_FROM_PARENT',NULL,'OPEN',info);
 RETURN jsonb_build_object('parent_wo_ref',meta.wo_ref,'child_wo_ref',child,'added_qty',p_added_qty,'carryover_qty',carry,'parent_actual',parent_actual,'remaining',p_added_qty-carry);
END $$;
CREATE OR REPLACE FUNCTION public.wo_attention_list() RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER AS $$
 WITH refs AS (
  SELECT m.wo_ref,m.wo_qty AS qty,m.wo_start_date AS start_date FROM public.wo_list_metadata() m
 ), all_refs AS (
  SELECT * FROM refs
 ), overview AS (
  SELECT r.*, coalesce(s.status,'OPEN') AS status, s.closed_at, s.closed_reason, s.note,
   (public.wo_progress(r.wo_ref)->>'total_progress')::numeric AS ok
  FROM all_refs r LEFT JOIN public.production_wo_status s ON public.wo_normalize(s.wo_ref)=public.wo_normalize(r.wo_ref)
 ), assignment AS (
  SELECT o.*, a.id AS assignment_id, a.line_code, a.product_code, a.product_name, a.effective_date, a.effective_shift,
   latest.tanggal AS latest_date, latest.shift AS latest_shift, latest.kode AS latest_code, latest.nama AS latest_name,
   prior.tanggal AS previous_date, prior.shift AS previous_shift,
   (latest.tanggal IS NOT NULL AND (public.wo_normalize(latest.kode) <> public.wo_normalize(a.product_code) OR public.wo_normalize(latest.nama) <> public.wo_normalize(a.product_name))) AS changed
  FROM overview o JOIN public.production_wo_assignments a ON public.wo_normalize(a.wo_ref)=public.wo_normalize(o.wo_ref) AND a.ended_date IS NULL
  LEFT JOIN LATERAL (
   SELECT l.tanggal, l.shift, l.kode, l.nama FROM public.logs l
   WHERE public.wo_normalize(l.line)=public.wo_normalize(a.line_code)
     AND (l.tanggal::date,l.shift::integer) >= (a.effective_date,a.effective_shift)
   ORDER BY l.tanggal DESC,l.shift::integer DESC, (to_jsonb(l)->>'created_at') DESC NULLS LAST,l.id DESC LIMIT 1
  ) latest ON true
  LEFT JOIN LATERAL (
   SELECT l.tanggal,l.shift FROM public.logs l WHERE public.wo_normalize(l.line)=public.wo_normalize(a.line_code)
    AND public.wo_normalize(l.kode)=public.wo_normalize(a.product_code) AND public.wo_normalize(l.nama)=public.wo_normalize(a.product_name)
    AND (l.tanggal::date,l.shift::integer) >= (a.effective_date,a.effective_shift)
    AND (public.wo_normalize(l.wo_ref)='' OR public.wo_normalize(l.wo_ref)=public.wo_normalize(o.wo_ref))
   ORDER BY l.tanggal DESC,l.shift::integer DESC,(to_jsonb(l)->>'created_at') DESC NULLS LAST,l.id DESC LIMIT 1
  ) prior ON true
 ), items AS (
  SELECT jsonb_build_object('wo_ref',o.wo_ref,'qty',o.qty,'ok',o.ok,'remaining',o.qty-o.ok,'status',o.status,'closed_at',o.closed_at,'reason',o.closed_reason,'note',o.note,
   'parent_ref',(SELECT c.parent_wo_ref FROM public.wo_continuation_read(o.wo_ref) c WHERE public.wo_normalize(c.child_wo_ref)=public.wo_normalize(o.wo_ref)),
   'child_ref',(SELECT c.child_wo_ref FROM public.wo_continuation_read(o.wo_ref) c WHERE public.wo_normalize(c.parent_wo_ref)=public.wo_normalize(o.wo_ref) LIMIT 1),
   'carryover_qty',coalesce((SELECT c.carryover_qty FROM public.wo_continuation_read(o.wo_ref) c WHERE public.wo_normalize(c.child_wo_ref)=public.wo_normalize(o.wo_ref)),0),
   'assignments',coalesce((SELECT jsonb_agg(to_jsonb(a) - 'qty' - 'ok' - 'status' - 'wo_ref' - 'closed_at' - 'closed_reason' - 'note') FROM assignment a WHERE public.wo_normalize(a.wo_ref)=public.wo_normalize(o.wo_ref)), '[]'::jsonb)) AS item
  FROM overview o
 ) SELECT coalesce(jsonb_agg(item),'[]'::jsonb) FROM items
$$;


-- Preserve established WO targets and prevent future edits from crossing a continuation boundary.
CREATE OR REPLACE FUNCTION public.wo_guard_log_continuation() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE target numeric; boundary record;
BEGIN
 IF public.wo_normalize(NEW.wo_ref) = '' THEN RETURN NEW; END IF;
 SELECT m.wo_qty INTO target FROM public.wo_metadata(NEW.wo_ref) m;
 IF target IS NOT NULL AND NEW.wo_qty IS DISTINCT FROM target THEN RAISE EXCEPTION 'Target WO tidak dapat diubah; gunakan WO Lanjutan'; END IF;
 SELECT effective_date,effective_shift INTO boundary FROM public.production_wo_continuations WHERE public.wo_normalize(parent_wo_ref)=public.wo_normalize(NEW.wo_ref);
 IF FOUND AND (NEW.tanggal::date,NEW.shift::integer)>=(boundary.effective_date,boundary.effective_shift) THEN RAISE EXCEPTION 'Laporan parent melewati boundary WO lanjutan'; END IF;
 SELECT effective_date,effective_shift INTO boundary FROM public.production_wo_continuations WHERE public.wo_normalize(child_wo_ref)=public.wo_normalize(NEW.wo_ref);
 IF FOUND AND (NEW.tanggal::date,NEW.shift::integer)<(boundary.effective_date,boundary.effective_shift) THEN RAISE EXCEPTION 'Laporan child sebelum boundary WO lanjutan'; END IF;
 RETURN NEW;
END $$;
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='wo_guard_log_continuation' AND tgrelid='public.logs'::regclass AND NOT tgisinternal) THEN
  CREATE TRIGGER wo_guard_log_continuation BEFORE INSERT OR UPDATE OF wo_ref,wo_qty,tanggal,shift ON public.logs FOR EACH ROW EXECUTE FUNCTION public.wo_guard_log_continuation();
 END IF;
END $$;

-- Freeze the production rows and assignment coverage behind a credited parent.
-- This includes legacy blank-reference logs matched by the same rules as wo_progress.
CREATE OR REPLACE FUNCTION public.wo_parent_snapshot_match(p_ref text,p_line text,p_code text,p_name text,p_date date,p_shift integer)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
 SELECT EXISTS (
  SELECT 1 FROM public.production_wo_continuations c
  JOIN public.production_wo_assignments a ON public.wo_normalize(a.wo_ref)=public.wo_normalize(c.parent_wo_ref)
  WHERE (public.wo_normalize(p_ref)='' OR public.wo_normalize(p_ref)=public.wo_normalize(c.parent_wo_ref))
   AND public.wo_normalize(p_line)=public.wo_normalize(a.line_code)
   AND public.wo_normalize(p_code)=public.wo_normalize(a.product_code)
   AND public.wo_normalize(p_name)=public.wo_normalize(a.product_name)
   AND (p_date,p_shift)>=(a.effective_date,a.effective_shift)
   AND (a.ended_date IS NULL OR (p_date,p_shift)<=(a.ended_date,a.ended_shift))
 )
$$;
CREATE OR REPLACE FUNCTION public.wo_freeze_parent_log() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
 IF TG_OP='UPDATE' AND ROW(OLD.wo_ref,OLD.line,OLD.kode,OLD.nama,OLD.tanggal,OLD.shift,OLD.okpcs) IS NOT DISTINCT FROM ROW(NEW.wo_ref,NEW.line,NEW.kode,NEW.nama,NEW.tanggal,NEW.shift,NEW.okpcs) THEN RETURN NEW; END IF;
 IF TG_OP IN ('UPDATE','DELETE') AND public.wo_parent_snapshot_match(OLD.wo_ref,OLD.line,OLD.kode,OLD.nama,OLD.tanggal::date,OLD.shift::integer) THEN RAISE EXCEPTION 'Laporan yang membentuk WO parent terkunci setelah WO lanjutan dibuat'; END IF;
 IF TG_OP IN ('UPDATE','INSERT') AND public.wo_parent_snapshot_match(NEW.wo_ref,NEW.line,NEW.kode,NEW.nama,NEW.tanggal::date,NEW.shift::integer) THEN RAISE EXCEPTION 'Produksi historis WO parent terkunci setelah WO lanjutan dibuat'; END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION public.wo_freeze_parent_assignment() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
 IF TG_OP IN ('UPDATE','DELETE') AND EXISTS (SELECT 1 FROM public.production_wo_continuations WHERE public.wo_normalize(parent_wo_ref)=public.wo_normalize(OLD.wo_ref)) THEN RAISE EXCEPTION 'Assignment WO parent terkunci setelah WO lanjutan dibuat'; END IF;
 IF TG_OP IN ('INSERT','UPDATE') AND EXISTS (SELECT 1 FROM public.production_wo_continuations WHERE public.wo_normalize(parent_wo_ref)=public.wo_normalize(NEW.wo_ref)) THEN RAISE EXCEPTION 'Assignment WO parent terkunci setelah WO lanjutan dibuat'; END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='wo_freeze_parent_log' AND tgrelid='public.logs'::regclass AND NOT tgisinternal) THEN
  CREATE TRIGGER wo_freeze_parent_log BEFORE INSERT OR UPDATE OR DELETE ON public.logs FOR EACH ROW EXECUTE FUNCTION public.wo_freeze_parent_log();
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='wo_freeze_parent_assignment' AND tgrelid='public.production_wo_assignments'::regclass AND NOT tgisinternal) THEN
  CREATE TRIGGER wo_freeze_parent_assignment BEFORE INSERT OR UPDATE OR DELETE ON public.production_wo_assignments FOR EACH ROW EXECUTE FUNCTION public.wo_freeze_parent_assignment();
 END IF;
END $$;

-- Register the first valid target in the same transaction as a new WO report.
CREATE OR REPLACE FUNCTION public.wo_register_target() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE existing numeric;
BEGIN
 IF public.wo_normalize(NEW.wo_ref)='' OR NEW.wo_qty IS NULL OR NEW.wo_qty<=0 THEN RETURN NEW; END IF;
 IF NEW.wo_start_date IS NULL OR NEW.wo_start_shift IS NULL THEN RAISE EXCEPTION 'Tanggal dan shift mulai WO wajib diisi'; END IF;
 INSERT INTO public.production_wo_targets (wo_ref,target_qty,start_date,start_shift,source)
 VALUES (btrim(NEW.wo_ref),NEW.wo_qty,NEW.wo_start_date::date,NEW.wo_start_shift::integer,'shift_report')
 ON CONFLICT ((public.wo_normalize(wo_ref))) DO NOTHING;
 SELECT t.target_qty INTO existing FROM public.production_wo_targets t WHERE public.wo_normalize(t.wo_ref)=public.wo_normalize(NEW.wo_ref);
 IF existing IS DISTINCT FROM NEW.wo_qty THEN RAISE EXCEPTION 'Target WO tidak dapat diubah; gunakan WO Lanjutan'; END IF;
 RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION public.wo_freeze_target() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Target WO tidak dapat dihapus'; END IF;
 IF NEW.wo_ref IS DISTINCT FROM OLD.wo_ref OR NEW.target_qty IS DISTINCT FROM OLD.target_qty THEN RAISE EXCEPTION 'Target WO tidak dapat diubah'; END IF;
 RETURN NEW;
END $$;
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='wo_register_target' AND tgrelid='public.logs'::regclass AND NOT tgisinternal) THEN
  CREATE TRIGGER wo_register_target BEFORE INSERT OR UPDATE OF wo_ref,wo_qty,wo_start_date,wo_start_shift ON public.logs FOR EACH ROW EXECUTE FUNCTION public.wo_register_target();
 END IF;
 IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='wo_freeze_target' AND tgrelid='public.production_wo_targets'::regclass AND NOT tgisinternal) THEN
  CREATE TRIGGER wo_freeze_target BEFORE UPDATE OR DELETE ON public.production_wo_targets FOR EACH ROW EXECUTE FUNCTION public.wo_freeze_target();
 END IF;
END $$;

