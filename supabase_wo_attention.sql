-- Run after the existing WO migrations. These functions use caller privileges and RLS.
CREATE TABLE IF NOT EXISTS public.production_wo_status (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 wo_ref text NOT NULL UNIQUE,
 status text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','ON_HOLD','CLOSED')),
 closed_reason text, note text, updated_at timestamptz NOT NULL DEFAULT now(), closed_at timestamptz, remaining_at_close numeric
);
CREATE UNIQUE INDEX IF NOT EXISTS wo_status_normalized_ref_idx ON public.production_wo_status (public.wo_normalize(wo_ref));
CREATE TABLE IF NOT EXISTS public.production_wo_actions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 wo_ref text NOT NULL, action text NOT NULL, previous_status text, new_status text,
 assignment_id bigint, note text, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS wo_actions_ref_idx ON public.production_wo_actions (public.wo_normalize(wo_ref), created_at DESC);

CREATE OR REPLACE FUNCTION public.wo_status_for_ref(p_ref text) RETURNS text LANGUAGE sql STABLE SECURITY INVOKER AS $$
 SELECT coalesce((SELECT s.status FROM public.production_wo_status s WHERE public.wo_normalize(s.wo_ref)=public.wo_normalize(p_ref)), 'OPEN')
$$;

CREATE OR REPLACE FUNCTION public.wo_attention_list() RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER AS $$
 WITH refs AS (
  SELECT DISTINCT ON (public.wo_normalize(l.wo_ref)) l.wo_ref::text AS wo_ref, l.wo_qty::numeric AS qty, l.wo_start_date::date AS start_date
  FROM public.logs l WHERE public.wo_normalize(l.wo_ref) <> '' AND l.wo_qty > 0 AND l.wo_start_date IS NOT NULL
  ORDER BY public.wo_normalize(l.wo_ref), l.tanggal DESC, l.shift DESC
 ), overview AS (
  SELECT r.*, coalesce(s.status,'OPEN') AS status, s.closed_at, s.closed_reason, s.note,
   (public.wo_progress(r.wo_ref)->>'historical_ok')::numeric AS ok
  FROM refs r LEFT JOIN public.production_wo_status s ON public.wo_normalize(s.wo_ref)=public.wo_normalize(r.wo_ref)
 ), assignment AS (
  SELECT o.*, a.id AS assignment_id, a.line_code, a.product_code, a.product_name, a.effective_date, a.effective_shift,
   latest.tanggal AS latest_date, latest.shift AS latest_shift, latest.kode AS latest_code, latest.nama AS latest_name,
   prior.tanggal AS previous_date, prior.shift AS previous_shift,
   (latest.tanggal IS NOT NULL AND (public.wo_normalize(latest.kode) <> public.wo_normalize(a.product_code) OR public.wo_normalize(latest.nama) <> public.wo_normalize(a.product_name))) AS changed
  FROM overview o JOIN public.production_wo_assignments a ON public.wo_normalize(a.wo_ref)=public.wo_normalize(o.wo_ref) AND a.ended_date IS NULL
  LEFT JOIN LATERAL (
   SELECT l.tanggal, l.shift, l.kode, l.nama FROM public.logs l
   WHERE public.wo_normalize(l.line)=public.wo_normalize(a.line_code)
     AND (l.tanggal::date,l.shift::integer) >= (a.effective_date,a.effective_shift)
   ORDER BY l.tanggal DESC,l.shift::integer DESC, (to_jsonb(l)->>'created_at') DESC NULLS LAST,l.id DESC LIMIT 1
  ) latest ON true
  LEFT JOIN LATERAL (
   SELECT l.tanggal,l.shift FROM public.logs l WHERE public.wo_normalize(l.line)=public.wo_normalize(a.line_code)
    AND public.wo_normalize(l.kode)=public.wo_normalize(a.product_code) AND public.wo_normalize(l.nama)=public.wo_normalize(a.product_name)
    AND (l.tanggal::date,l.shift::integer) >= (a.effective_date,a.effective_shift)
    AND (public.wo_normalize(l.wo_ref)='' OR public.wo_normalize(l.wo_ref)=public.wo_normalize(o.wo_ref))
   ORDER BY l.tanggal DESC,l.shift::integer DESC,(to_jsonb(l)->>'created_at') DESC NULLS LAST,l.id DESC LIMIT 1
  ) prior ON true
 ), items AS (
  SELECT jsonb_build_object('wo_ref',o.wo_ref,'qty',o.qty,'ok',o.ok,'remaining',o.qty-o.ok,'status',o.status,'closed_at',o.closed_at,'reason',o.closed_reason,'note',o.note,
   'assignments',coalesce((SELECT jsonb_agg(to_jsonb(a) - 'qty' - 'ok' - 'status' - 'wo_ref' - 'closed_at' - 'closed_reason' - 'note') FROM assignment a WHERE public.wo_normalize(a.wo_ref)=public.wo_normalize(o.wo_ref)), '[]'::jsonb)) AS item
  FROM overview o
 ) SELECT coalesce(jsonb_agg(item),'[]'::jsonb) FROM items
$$;

CREATE OR REPLACE FUNCTION public.wo_admin_status(p_ref text,p_status text,p_action text,p_reason text DEFAULT NULL,p_note text DEFAULT NULL,p_remaining numeric DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY INVOKER AS $$
DECLARE previous text;
BEGIN
 IF public.wo_normalize(p_ref)='' OR p_status NOT IN ('OPEN','ON_HOLD','CLOSED') OR p_action NOT IN ('KEEP_OPEN','HOLD','CLOSE','REOPEN') THEN RAISE EXCEPTION 'Status tidak valid'; END IF;
 IF p_status='CLOSED' AND coalesce(btrim(p_reason),'')='' THEN RAISE EXCEPTION 'Alasan penutupan wajib diisi'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(public.wo_normalize(p_ref),0));
 previous := public.wo_status_for_ref(p_ref);
 INSERT INTO public.production_wo_status (wo_ref,status,closed_reason,note,updated_at,closed_at,remaining_at_close)
 VALUES (btrim(p_ref),p_status,CASE WHEN p_status='CLOSED' THEN p_reason END,p_note,now(),CASE WHEN p_status='CLOSED' THEN now() END,CASE WHEN p_status='CLOSED' THEN p_remaining END)
 ON CONFLICT ((public.wo_normalize(wo_ref))) DO UPDATE SET status=excluded.status,closed_reason=excluded.closed_reason,note=excluded.note,updated_at=excluded.updated_at,closed_at=excluded.closed_at,remaining_at_close=excluded.remaining_at_close;
 INSERT INTO public.production_wo_actions(wo_ref,action,previous_status,new_status,note) VALUES (btrim(p_ref),p_action,previous,p_status,concat_ws(' — ',nullif(p_reason,''),nullif(p_note,'')));
END $$;

CREATE OR REPLACE FUNCTION public.wo_admin_assignment(p_ref text,p_action text,p_source bigint,p_line text DEFAULT NULL,p_code text DEFAULT NULL,p_name text DEFAULT NULL,p_date date DEFAULT NULL,p_shift integer DEFAULT NULL,p_note text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY INVOKER AS $$
DECLARE source public.production_wo_assignments%ROWTYPE; previous text; v_end_date date; v_end_shift integer;
BEGIN
 IF p_action NOT IN ('TRANSFER','PARALLEL','END_ASSIGNMENT') OR p_date IS NULL OR p_shift IS NULL OR p_shift NOT BETWEEN 1 AND 3 THEN RAISE EXCEPTION 'Aksi atau waktu tidak valid'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(public.wo_normalize(p_ref),0));
 previous := public.wo_status_for_ref(p_ref);
 IF previous='CLOSED' THEN RAISE EXCEPTION 'WO sudah ditutup'; END IF;
 IF p_action IN ('TRANSFER','END_ASSIGNMENT') THEN
  SELECT * INTO source FROM public.production_wo_assignments a WHERE a.id=p_source AND public.wo_normalize(a.wo_ref)=public.wo_normalize(p_ref) AND a.ended_date IS NULL FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Assignment asal tidak tersedia'; END IF;
  v_end_date := CASE WHEN p_shift=1 THEN p_date-1 ELSE p_date END; v_end_shift := CASE WHEN p_shift=1 THEN 3 ELSE p_shift-1 END;
  IF (v_end_date,v_end_shift)<(source.effective_date,source.effective_shift) THEN RAISE EXCEPTION 'Waktu harus setelah awal assignment'; END IF;
 END IF;
 IF p_action='END_ASSIGNMENT' THEN
  UPDATE public.production_wo_assignments SET ended_date=v_end_date, ended_shift=v_end_shift WHERE id=p_source;
 ELSE
  IF coalesce(btrim(p_line),'')='' OR coalesce(btrim(p_code),'')='' OR coalesce(btrim(p_name),'')='' THEN RAISE EXCEPTION 'Mesin dan produk wajib diisi'; END IF;
  PERFORM public.create_wo_assignment(p_ref,p_line,p_code,p_name,p_date,p_shift::smallint,CASE WHEN p_action='TRANSFER' THEN p_source ELSE NULL END);
 END IF;
 IF p_action <> 'END_ASSIGNMENT' THEN
  INSERT INTO public.production_wo_status (wo_ref,status,updated_at) VALUES (btrim(p_ref),'OPEN',now())
  ON CONFLICT ((public.wo_normalize(wo_ref))) DO UPDATE SET status='OPEN',updated_at=now(),closed_at=NULL,closed_reason=NULL,remaining_at_close=NULL;
 END IF;
 INSERT INTO public.production_wo_actions(wo_ref,action,previous_status,new_status,assignment_id,note) VALUES (btrim(p_ref),p_action,previous,CASE WHEN p_action='END_ASSIGNMENT' THEN previous ELSE 'OPEN' END,p_source,p_note);
END $$;

CREATE OR REPLACE FUNCTION public.wo_list_open_metadata()
RETURNS TABLE (wo_ref text, wo_qty numeric, wo_start_date date, wo_start_shift integer)
LANGUAGE sql STABLE SECURITY INVOKER AS $$
 SELECT m.wo_ref,m.wo_qty,m.wo_start_date,m.wo_start_shift FROM public.wo_list_metadata() m WHERE public.wo_status_for_ref(m.wo_ref)='OPEN'
$$;
