-- Install after the existing WO, attention, performance and continuation migrations.
-- No production logs are changed by these functions. PIN remains a UI control;
-- authorization of anon/authenticated RPC callers requires a separate Auth/RLS design.
-- Admin-approved history. Child blank logs require an explicit segment;
-- logs themselves and existing continuation/carry-over snapshots remain unchanged.
CREATE TABLE IF NOT EXISTS public.production_wo_history_links (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 wo_ref text NOT NULL, assignment_id bigint NOT NULL REFERENCES public.production_wo_assignments(id),
 line_code text NOT NULL, product_code text NOT NULL, product_name text NOT NULL,
 effective_date date NOT NULL, effective_shift integer NOT NULL CHECK (effective_shift BETWEEN 1 AND 3),
 ended_date date NOT NULL, ended_shift integer NOT NULL CHECK (ended_shift BETWEEN 1 AND 3),
 source text NOT NULL DEFAULT 'ADD_PARALLEL_WITH_HISTORY', created_at timestamptz NOT NULL DEFAULT now(),
 CHECK ((ended_date,ended_shift)>=(effective_date,effective_shift))
);
CREATE INDEX IF NOT EXISTS wo_history_links_assignment_idx ON public.production_wo_history_links (assignment_id,effective_date,effective_shift,ended_date,ended_shift);
CREATE INDEX IF NOT EXISTS wo_history_links_identity_idx ON public.production_wo_history_links (public.wo_normalize(line_code),public.wo_normalize(product_code),public.wo_normalize(product_name),effective_date,effective_shift);
REVOKE ALL ON TABLE public.production_wo_history_links FROM PUBLIC, anon, authenticated;

-- A blank log is protected when another WO has assignment or approved
-- history-link coverage for the exact line, full product and shift boundary.
CREATE OR REPLACE FUNCTION public.wo_blank_owned_by_other(p_ref text,p_line text,p_code text,p_name text,p_date date,p_shift integer)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
 SELECT EXISTS (SELECT 1 FROM public.production_wo_assignments pa
  WHERE public.wo_normalize(pa.wo_ref)<>public.wo_normalize(p_ref)
   AND public.wo_normalize(pa.line_code)=public.wo_normalize(p_line)
   AND public.wo_normalize(pa.product_code)=public.wo_normalize(p_code)
   AND public.wo_normalize(pa.product_name)=public.wo_normalize(p_name)
   AND (p_date,p_shift)>=(pa.effective_date,pa.effective_shift)
   AND (pa.ended_date IS NULL OR (p_date,p_shift)<=(pa.ended_date,pa.ended_shift)))
 OR EXISTS (SELECT 1 FROM public.production_wo_history_links h
  WHERE public.wo_normalize(h.wo_ref)<>public.wo_normalize(p_ref)
   AND public.wo_normalize(h.line_code)=public.wo_normalize(p_line)
   AND public.wo_normalize(h.product_code)=public.wo_normalize(p_code)
   AND public.wo_normalize(h.product_name)=public.wo_normalize(p_name)
   AND (p_date,p_shift)>=(h.effective_date,h.effective_shift)
   AND (p_date,p_shift)<=(h.ended_date,h.ended_shift))
$$;

-- The caller still has to match an assignment and blank reference. This helper
-- exposes only whether a specific approved segment covers a production boundary.
CREATE OR REPLACE FUNCTION public.wo_history_link_covers(p_ref text,p_assignment_id bigint,p_line text,p_code text,p_name text,p_date date,p_shift integer)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
 SELECT EXISTS (SELECT 1 FROM public.production_wo_history_links h
  JOIN public.production_wo_continuations c ON public.wo_normalize(c.child_wo_ref)=public.wo_normalize(h.wo_ref)
  WHERE h.assignment_id=p_assignment_id AND public.wo_normalize(h.wo_ref)=public.wo_normalize(p_ref)
   AND public.wo_normalize(h.line_code)=public.wo_normalize(p_line) AND public.wo_normalize(h.product_code)=public.wo_normalize(p_code) AND public.wo_normalize(h.product_name)=public.wo_normalize(p_name)
   AND (p_date,p_shift)>=(h.effective_date,h.effective_shift) AND (p_date,p_shift)<=(h.ended_date,h.ended_shift)
   AND (p_date,p_shift)>=(c.effective_date,c.effective_shift)
   AND NOT public.wo_blank_owned_by_other(p_ref,p_line,p_code,p_name,p_date,p_shift))
$$;

-- Prevent a later assignment for another ordinary WO from silently claiming
-- blank logs already approved for a child, or vice versa.
CREATE OR REPLACE FUNCTION public.wo_guard_history_link_assignment() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
 IF TG_OP='UPDATE' THEN
  IF EXISTS (SELECT 1 FROM public.production_wo_history_links h WHERE h.assignment_id=OLD.id) AND
   ROW(OLD.wo_ref,OLD.line_code,OLD.product_code,OLD.product_name,OLD.effective_date,OLD.effective_shift,OLD.ended_date,OLD.ended_shift)
    IS DISTINCT FROM ROW(NEW.wo_ref,NEW.line_code,NEW.product_code,NEW.product_name,NEW.effective_date,NEW.effective_shift,NEW.ended_date,NEW.ended_shift) THEN
   RAISE EXCEPTION 'Assignment dengan histori child yang disetujui tidak dapat diubah'; END IF;
 END IF;
 IF EXISTS (SELECT 1 FROM public.production_wo_history_links h
  WHERE public.wo_normalize(h.wo_ref)<>public.wo_normalize(NEW.wo_ref)
   AND public.wo_normalize(h.line_code)=public.wo_normalize(NEW.line_code)
   AND public.wo_normalize(h.product_code)=public.wo_normalize(NEW.product_code)
   AND public.wo_normalize(h.product_name)=public.wo_normalize(NEW.product_name)
   AND (NEW.effective_date,NEW.effective_shift)<=(h.ended_date,h.ended_shift)
   AND (coalesce(NEW.ended_date,'infinity'::date),coalesce(NEW.ended_shift,2147483647))>=(h.effective_date,h.effective_shift)) THEN
  RAISE EXCEPTION 'Assignment bertabrakan dengan histori child WO yang sudah disetujui'; END IF;
 RETURN NEW;
END $$;
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='wo_guard_history_link_assignment' AND tgrelid='public.production_wo_assignments'::regclass AND NOT tgisinternal) THEN
  CREATE TRIGGER wo_guard_history_link_assignment BEFORE INSERT OR UPDATE OF wo_ref,line_code,product_code,product_name,effective_date,effective_shift,ended_date,ended_shift ON public.production_wo_assignments FOR EACH ROW EXECUTE FUNCTION public.wo_guard_history_link_assignment();
 END IF;
END $$;

CREATE OR REPLACE FUNCTION public.wo_progress(p_ref text, p_exclude_id text DEFAULT NULL, p_draft jsonb DEFAULT NULL, p_transfer_id bigint DEFAULT NULL)
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER AS $$
 WITH assignment AS (
   SELECT a.id AS assignment_id, a.line_code, a.product_code, a.product_name, a.effective_date, a.effective_shift,
     CASE WHEN a.id = p_transfer_id AND p_draft IS NOT NULL THEN
       CASE WHEN (p_draft->>'effective_shift')::integer = 1 THEN (p_draft->>'effective_date')::date - 1 ELSE (p_draft->>'effective_date')::date END
       ELSE a.ended_date END AS ended_date,
     CASE WHEN a.id = p_transfer_id AND p_draft IS NOT NULL THEN
       CASE WHEN (p_draft->>'effective_shift')::integer = 1 THEN 3 ELSE (p_draft->>'effective_shift')::integer - 1 END
       ELSE a.ended_shift END AS ended_shift
   FROM public.production_wo_assignments a WHERE public.wo_normalize(a.wo_ref) = public.wo_normalize(p_ref)
   UNION ALL
   SELECT NULL::bigint, p_draft->>'line_code', p_draft->>'product_code', p_draft->>'product_name',
     (p_draft->>'effective_date')::date, (p_draft->>'effective_shift')::integer, NULL::date, NULL::integer
   WHERE p_draft IS NOT NULL
 ), matched AS (
   SELECT l.line, l.kode, l.nama, l.okpcs, l.wo_ref
   FROM public.logs l
   WHERE (p_exclude_id IS NULL OR l.id::text <> p_exclude_id)
     AND EXISTS (SELECT 1 FROM assignment a
       WHERE (public.wo_normalize(l.wo_ref) = public.wo_normalize(p_ref) OR
        (public.wo_normalize(l.wo_ref) = '' AND (NOT EXISTS (SELECT 1 FROM public.wo_continuation_read(p_ref) c WHERE public.wo_normalize(c.child_wo_ref)=public.wo_normalize(p_ref)) OR public.wo_history_link_covers(p_ref,a.assignment_id,l.line,l.kode,l.nama,l.tanggal::date,l.shift::integer))))
         AND public.wo_normalize(l.line) = public.wo_normalize(a.line_code)
         AND public.wo_normalize(l.kode) = public.wo_normalize(a.product_code)
         AND public.wo_normalize(l.nama) = public.wo_normalize(a.product_name)
         AND (l.tanggal::date, l.shift::integer) >= (a.effective_date, a.effective_shift)
         AND (a.ended_date IS NULL OR (l.tanggal::date, l.shift::integer) <= (a.ended_date, a.ended_shift)))
 ), grouped AS (
   SELECT line, kode, nama, sum(coalesce(okpcs,0)) AS ok FROM matched GROUP BY line,kode,nama
 )
 SELECT jsonb_build_object('historical_ok', coalesce((SELECT sum(coalesce(okpcs,0)) FROM matched),0),
   'includes_unreferenced', coalesce((SELECT bool_or(public.wo_normalize(wo_ref) = '') FROM matched),false),
   'is_continuation', EXISTS (SELECT 1 FROM public.wo_continuation_read(p_ref) WHERE public.wo_normalize(child_wo_ref)=public.wo_normalize(p_ref)),
   'production_ok', coalesce((SELECT sum(coalesce(okpcs,0)) FROM matched),0),
   'carryover_qty', coalesce((SELECT carryover_qty FROM public.wo_continuation_read(p_ref) WHERE public.wo_normalize(child_wo_ref)=public.wo_normalize(p_ref)),0),
   'total_progress', coalesce((SELECT sum(coalesce(okpcs,0)) FROM matched),0) + coalesce((SELECT carryover_qty FROM public.wo_continuation_read(p_ref) WHERE public.wo_normalize(child_wo_ref)=public.wo_normalize(p_ref)),0),
   'remaining', (SELECT wo_qty FROM public.wo_metadata(p_ref)) - coalesce((SELECT sum(coalesce(okpcs,0)) FROM matched),0) - coalesce((SELECT carryover_qty FROM public.wo_continuation_read(p_ref) WHERE public.wo_normalize(child_wo_ref)=public.wo_normalize(p_ref)),0),
   'contributions', coalesce((SELECT jsonb_agg(jsonb_build_object('line',line,'kode',kode,'nama',nama,'ok',ok)) FROM grouped),'[]'::jsonb))
$$;


CREATE OR REPLACE FUNCTION public.wo_repair_preview(
 p_mode text, p_ref text, p_assignment_id bigint, p_line text, p_code text,
 p_name text, p_date date, p_shift integer, p_include_history boolean DEFAULT false
) RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
 v_meta record; v_assignment public.production_wo_assignments%ROWTYPE;
 v_start_date date; v_start_shift integer; v_end_date date; v_end_shift integer;
 v_first_date date; v_first_shift integer; v_last_date date; v_last_shift integer;
 v_count bigint; v_candidate_ok numeric; v_before numeric; v_after numeric;
 v_is_child boolean; v_carry numeric; v_result jsonb; v_fingerprint text; v_assignment_fingerprint text; v_relevant_fingerprint text; v_history_fingerprint text;
 v_protected_count bigint; v_protected_ok numeric; v_blocking_count bigint; v_ownership_conflicts bigint;
BEGIN
 IF p_mode IS NULL OR p_mode NOT IN ('CORRECT','PARALLEL') OR public.wo_normalize(p_ref)='' OR public.wo_normalize(p_code)='' OR public.wo_normalize(p_name)='' THEN RAISE EXCEPTION 'Data WO atau produk tidak lengkap'; END IF;
 IF public.wo_status_for_ref(p_ref)='CLOSED' THEN RAISE EXCEPTION 'WO CLOSED tidak dapat diperbaiki'; END IF;
 SELECT * INTO v_meta FROM public.wo_metadata(p_ref);
 IF NOT FOUND OR v_meta.wo_start_date IS NULL OR v_meta.wo_start_shift IS NULL THEN RAISE EXCEPTION 'Metadata WO tidak tersedia'; END IF;
 IF NOT EXISTS (SELECT 1 FROM public.master m WHERE public.wo_normalize(m.kode)=public.wo_normalize(p_code) AND public.wo_normalize(m.nama)=public.wo_normalize(p_name)) THEN RAISE EXCEPTION 'Produk tidak ditemukan secara exact di master'; END IF;
 SELECT EXISTS (SELECT 1 FROM public.wo_continuation_read(p_ref) c WHERE public.wo_normalize(c.child_wo_ref)=public.wo_normalize(p_ref)) INTO v_is_child;
 IF p_mode='CORRECT' THEN
  SELECT * INTO v_assignment FROM public.production_wo_assignments pa WHERE pa.id=p_assignment_id AND public.wo_normalize(pa.wo_ref)=public.wo_normalize(p_ref);
  IF NOT FOUND THEN RAISE EXCEPTION 'Assignment tidak ditemukan pada WO ini'; END IF;
  IF EXISTS (SELECT 1 FROM public.production_wo_history_links h WHERE h.assignment_id=p_assignment_id) THEN RAISE EXCEPTION 'Assignment memiliki histori disetujui; koreksi memerlukan peninjauan terpisah'; END IF;
  IF public.wo_normalize(v_assignment.product_code)=public.wo_normalize(p_code) AND public.wo_normalize(v_assignment.product_name)=public.wo_normalize(p_name) THEN RAISE EXCEPTION 'Produk pengganti sama dengan produk assignment'; END IF;
  p_line:=v_assignment.line_code; v_start_date:=v_assignment.effective_date; v_start_shift:=v_assignment.effective_shift;
  v_end_date:=v_assignment.ended_date; v_end_shift:=v_assignment.ended_shift;
 ELSE
  IF public.wo_normalize(p_line)='' OR p_date IS NULL OR p_shift IS NULL OR p_shift NOT BETWEEN 1 AND 3 OR (p_date,p_shift)<(v_meta.wo_start_date,v_meta.wo_start_shift) THEN RAISE EXCEPTION 'Mesin dan boundary harus valid dan tidak sebelum awal WO'; END IF;
  v_start_date:=p_date; v_start_shift:=p_shift; v_end_date:=NULL; v_end_shift:=NULL;
 END IF;
 -- Split protected blank rows from candidates before calculating any totals.
 WITH candidate_all AS MATERIALIZED (
  SELECT l.id::text AS id,l.tanggal::date AS tanggal,l.shift::integer AS shift,l.okpcs,l.wo_ref,
   (public.wo_normalize(l.wo_ref)='' AND public.wo_blank_owned_by_other(p_ref,l.line,l.kode,l.nama,l.tanggal::date,l.shift::integer)) AS protected
  FROM public.logs l
  WHERE public.wo_normalize(l.line)=public.wo_normalize(p_line)
   AND public.wo_normalize(l.kode)=public.wo_normalize(p_code)
   AND public.wo_normalize(l.nama)=public.wo_normalize(p_name)
   AND (public.wo_normalize(l.wo_ref)=public.wo_normalize(p_ref) OR (public.wo_normalize(l.wo_ref)='' AND (NOT v_is_child OR p_mode='PARALLEL')))
   AND CASE WHEN p_mode='PARALLEL' THEN
    (l.tanggal::date,l.shift::integer)>=(v_meta.wo_start_date,v_meta.wo_start_shift) AND (l.tanggal::date,l.shift::integer)<(p_date,p_shift)
   ELSE (l.tanggal::date,l.shift::integer)>=(v_start_date,v_start_shift)
    AND (v_end_date IS NULL OR (l.tanggal::date,l.shift::integer)<=(v_end_date,v_end_shift)) END
 ), candidate AS MATERIALIZED (SELECT * FROM candidate_all WHERE NOT protected)
 SELECT count(*),coalesce(sum(coalesce(c.okpcs,0)),0),
  (SELECT x.tanggal FROM candidate x ORDER BY x.tanggal,x.shift LIMIT 1),
  (SELECT x.shift FROM candidate x ORDER BY x.tanggal,x.shift LIMIT 1),
  (SELECT x.tanggal FROM candidate x ORDER BY x.tanggal DESC,x.shift DESC LIMIT 1),
  (SELECT x.shift FROM candidate x ORDER BY x.tanggal DESC,x.shift DESC LIMIT 1),
  md5(coalesce(string_agg(md5(jsonb_build_array(c.id,c.tanggal,c.shift,c.okpcs,c.wo_ref)::text),',' ORDER BY c.id),'')),
  (SELECT count(*) FROM candidate_all x WHERE x.protected),
  (SELECT coalesce(sum(coalesce(x.okpcs,0)),0) FROM candidate_all x WHERE x.protected)
 INTO v_count,v_candidate_ok,v_first_date,v_first_shift,v_last_date,v_last_shift,v_fingerprint,v_protected_count,v_protected_ok FROM candidate c;
 IF p_mode='PARALLEL' AND p_include_history AND v_count>0 THEN v_start_date:=v_first_date; v_start_shift:=v_first_shift; END IF;
 IF p_mode='PARALLEL' AND p_include_history AND v_is_child AND v_count>0 AND EXISTS (
  SELECT 1 FROM public.production_wo_assignments other
  WHERE public.wo_normalize(other.wo_ref)<>public.wo_normalize(p_ref)
   AND public.wo_normalize(other.line_code)=public.wo_normalize(p_line)
   AND public.wo_normalize(other.product_code)=public.wo_normalize(p_code)
   AND public.wo_normalize(other.product_name)=public.wo_normalize(p_name)
   AND (other.effective_date,other.effective_shift)<(p_date,p_shift)
   AND (coalesce(other.ended_date,'infinity'::date),coalesce(other.ended_shift,2147483647))>=(v_first_date,v_first_shift)) THEN
  RAISE EXCEPTION 'Histori bertabrakan dengan assignment WO lain; periksa boundary sebelum melanjutkan'; END IF;
 SELECT md5(coalesce(string_agg(md5(to_jsonb(pa)::text),',' ORDER BY pa.id),'')) INTO v_assignment_fingerprint
 FROM public.production_wo_assignments pa WHERE public.wo_normalize(pa.wo_ref)=public.wo_normalize(p_ref)
  OR (public.wo_normalize(pa.line_code)=public.wo_normalize(p_line) AND public.wo_normalize(pa.product_code)=public.wo_normalize(p_code) AND public.wo_normalize(pa.product_name)=public.wo_normalize(p_name));
 SELECT md5(coalesce(string_agg(md5(to_jsonb(h)::text),',' ORDER BY h.id),'')) INTO v_history_fingerprint
 FROM public.production_wo_history_links h WHERE public.wo_normalize(h.line_code)=public.wo_normalize(p_line)
  AND public.wo_normalize(h.product_code)=public.wo_normalize(p_code) AND public.wo_normalize(h.product_name)=public.wo_normalize(p_name);
 -- The old normal-WO progress rule counts all blank logs within an assignment.
 -- Refuse to apply any new coverage containing protected blanks; excluding them
 -- only from preview would make committed progress differ from the preview.
 SELECT count(*) INTO v_blocking_count FROM public.logs l
 WHERE public.wo_normalize(l.wo_ref)='' AND public.wo_normalize(l.line)=public.wo_normalize(p_line)
  AND public.wo_normalize(l.kode)=public.wo_normalize(p_code) AND public.wo_normalize(l.nama)=public.wo_normalize(p_name)
  AND (l.tanggal::date,l.shift::integer)>=(v_start_date,v_start_shift)
  AND (v_end_date IS NULL OR (l.tanggal::date,l.shift::integer)<=(v_end_date,v_end_shift))
  AND public.wo_blank_owned_by_other(p_ref,l.line,l.kode,l.nama,l.tanggal::date,l.shift::integer);
 -- Even without blank logs today, overlapping another WO's assignment or
 -- approved link would permit a later historical blank to be claimed twice.
 SELECT (SELECT count(*) FROM public.production_wo_assignments other
  WHERE public.wo_normalize(other.wo_ref)<>public.wo_normalize(p_ref)
   AND public.wo_normalize(other.line_code)=public.wo_normalize(p_line)
   AND public.wo_normalize(other.product_code)=public.wo_normalize(p_code)
   AND public.wo_normalize(other.product_name)=public.wo_normalize(p_name)
   AND (other.effective_date,other.effective_shift)<=(coalesce(v_end_date,'infinity'::date),coalesce(v_end_shift,2147483647))
   AND (coalesce(other.ended_date,'infinity'::date),coalesce(other.ended_shift,2147483647))>=(v_start_date,v_start_shift))
 + (SELECT count(*) FROM public.production_wo_history_links h
  WHERE public.wo_normalize(h.wo_ref)<>public.wo_normalize(p_ref)
   AND public.wo_normalize(h.line_code)=public.wo_normalize(p_line)
   AND public.wo_normalize(h.product_code)=public.wo_normalize(p_code)
   AND public.wo_normalize(h.product_name)=public.wo_normalize(p_name)
   AND (h.effective_date,h.effective_shift)<=(coalesce(v_end_date,'infinity'::date),coalesce(v_end_shift,2147483647))
   AND (h.ended_date,h.ended_shift)>=(v_start_date,v_start_shift)) INTO v_ownership_conflicts;
 -- Fingerprint relevant logs as well as totals, so a same-total replacement or
 -- boundary/reference edit cannot make an old preview silently valid.
 SELECT md5(coalesce(string_agg(md5(jsonb_build_array(l.id,l.wo_ref,l.line,l.kode,l.nama,l.tanggal,l.shift,l.okpcs)::text),',' ORDER BY l.id::text),'')) INTO v_relevant_fingerprint
 FROM public.logs l WHERE public.wo_normalize(l.line) IN (
  SELECT public.wo_normalize(pa.line_code) FROM public.production_wo_assignments pa WHERE public.wo_normalize(pa.wo_ref)=public.wo_normalize(p_ref)
  UNION SELECT public.wo_normalize(p_line));

 -- Reject overlapping coverage for this exact WO + line + code + full name.
 IF EXISTS (SELECT 1 FROM public.production_wo_assignments pa
  WHERE public.wo_normalize(pa.wo_ref)=public.wo_normalize(p_ref)
   AND (p_mode<>'CORRECT' OR pa.id<>p_assignment_id)
   AND public.wo_normalize(pa.line_code)=public.wo_normalize(p_line)
   AND public.wo_normalize(pa.product_code)=public.wo_normalize(p_code)
   AND public.wo_normalize(pa.product_name)=public.wo_normalize(p_name)
   AND (pa.effective_date,pa.effective_shift)<=(coalesce(v_end_date,'infinity'::date),coalesce(v_end_shift,2147483647))
   AND (coalesce(pa.ended_date,'infinity'::date),coalesce(pa.ended_shift,2147483647))>=(v_start_date,v_start_shift)) THEN RAISE EXCEPTION 'Assignment produk dan mesin ini bertumpang tindih'; END IF;
 v_before:=(public.wo_progress(p_ref)->>'total_progress')::numeric;
 v_carry:=coalesce((SELECT c.carryover_qty FROM public.wo_continuation_read(p_ref) c WHERE public.wo_normalize(c.child_wo_ref)=public.wo_normalize(p_ref)),0);
 -- Simulate replacing or adding assignment, preserving the existing wo_progress
 -- EXISTS semantics, child credit and exclusion of other WO references.
 WITH coverage AS (
  SELECT pa.id AS assignment_id,pa.line_code,pa.product_code,pa.product_name,pa.effective_date,pa.effective_shift,pa.ended_date,pa.ended_shift
  FROM public.production_wo_assignments pa WHERE public.wo_normalize(pa.wo_ref)=public.wo_normalize(p_ref)
   AND (p_mode<>'CORRECT' OR pa.id<>p_assignment_id)
  UNION ALL SELECT NULL::bigint,p_line,p_code,p_name,v_start_date,v_start_shift,v_end_date,v_end_shift
 ), matched AS (
  SELECT l.okpcs FROM public.logs l
  WHERE EXISTS (SELECT 1 FROM coverage c WHERE
    (public.wo_normalize(l.wo_ref)=public.wo_normalize(p_ref) OR
     (public.wo_normalize(l.wo_ref)='' AND (
      (c.assignment_id IS NOT NULL AND (NOT v_is_child OR public.wo_history_link_covers(p_ref,c.assignment_id,l.line,l.kode,l.nama,l.tanggal::date,l.shift::integer))) OR
      (c.assignment_id IS NULL AND NOT public.wo_blank_owned_by_other(p_ref,l.line,l.kode,l.nama,l.tanggal::date,l.shift::integer)
       AND (NOT v_is_child OR (p_mode='PARALLEL' AND p_include_history AND (l.tanggal::date,l.shift::integer)<(p_date,p_shift)))))))
    AND public.wo_normalize(c.line_code)=public.wo_normalize(l.line)
    AND public.wo_normalize(c.product_code)=public.wo_normalize(l.kode) AND public.wo_normalize(c.product_name)=public.wo_normalize(l.nama)
    AND (l.tanggal::date,l.shift::integer)>=(c.effective_date,c.effective_shift)
    AND (c.ended_date IS NULL OR (l.tanggal::date,l.shift::integer)<=(c.ended_date,c.ended_shift)))
 ) SELECT coalesce(sum(coalesce(m.okpcs,0)),0)+v_carry INTO v_after FROM matched m;
 v_result:=jsonb_build_object('mode',p_mode,'wo_ref',v_meta.wo_ref,'assignment_id',CASE WHEN p_mode='CORRECT' THEN v_assignment.id ELSE NULL END,
  'line',p_line,'old_code',CASE WHEN p_mode='CORRECT' THEN v_assignment.product_code ELSE NULL END,'old_name',CASE WHEN p_mode='CORRECT' THEN v_assignment.product_name ELSE NULL END,
  'code',p_code,'name',p_name,'effective_date',v_start_date,'effective_shift',v_start_shift,'ended_date',v_end_date,'ended_shift',v_end_shift,
  'normal_date',CASE WHEN p_mode='PARALLEL' THEN p_date ELSE NULL END,'normal_shift',CASE WHEN p_mode='PARALLEL' THEN p_shift ELSE NULL END,
  'include_history',coalesce(p_include_history,false),'candidate_count',v_count,'candidate_ok',v_candidate_ok,'protected_other_wo_count',v_protected_count,'protected_other_wo_ok',v_protected_ok,'blocking_protected_count',v_blocking_count,'blocking_ownership_conflicts',v_ownership_conflicts,
  'first_date',v_first_date,'first_shift',v_first_shift,'last_date',v_last_date,'last_shift',v_last_shift,
  'progress_before',v_before,'production_before',v_before-v_carry,'carryover_qty',v_carry,'is_continuation',v_is_child,'child_effective_date',CASE WHEN v_is_child THEN v_meta.wo_start_date ELSE NULL END,'child_effective_shift',CASE WHEN v_is_child THEN v_meta.wo_start_shift ELSE NULL END,'progress_after',v_after,'projected_remaining',v_meta.wo_qty-v_after,'progress_delta',v_after-v_before,'candidate_fingerprint',v_fingerprint,'assignment_fingerprint',v_assignment_fingerprint,'history_links_fingerprint',v_history_fingerprint,'relevant_logs_fingerprint',v_relevant_fingerprint,'status',public.wo_status_for_ref(p_ref),'target',v_meta.wo_qty);
 RETURN v_result;
END $$;

CREATE OR REPLACE FUNCTION public.wo_repair_apply(
 p_mode text, p_ref text, p_assignment_id bigint, p_line text, p_code text, p_name text,
 p_date date, p_shift integer, p_include_history boolean, p_expected jsonb, p_note text DEFAULT NULL
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE v_preview jsonb; v_assignment_id bigint; v_historical_id bigint; v_date date; v_shift integer; v_end_date date; v_end_shift integer; v_status text;
BEGIN
 IF p_expected IS NULL THEN RAISE EXCEPTION 'Preview harus dikonfirmasi terlebih dahulu'; END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended(public.wo_normalize(p_ref),0));
 LOCK TABLE public.logs IN SHARE ROW EXCLUSIVE MODE;
 LOCK TABLE public.production_wo_assignments IN SHARE ROW EXCLUSIVE MODE;
 LOCK TABLE public.production_wo_history_links IN SHARE ROW EXCLUSIVE MODE;
 v_preview:=public.wo_repair_preview(p_mode,p_ref,p_assignment_id,p_line,p_code,p_name,p_date,p_shift,p_include_history);
 IF v_preview IS DISTINCT FROM p_expected THEN RAISE EXCEPTION 'Data WO berubah sejak preview; ulangi preview sebelum menyimpan'; END IF;
 IF (v_preview->>'blocking_protected_count')::bigint>0 OR (v_preview->>'blocking_ownership_conflicts')::bigint>0 THEN RAISE EXCEPTION 'Boundary bertabrakan dengan cakupan atau log yang dilindungi WO lain; pilih boundary lain'; END IF;
 v_status:=public.wo_status_for_ref(p_ref);
 IF p_mode='CORRECT' THEN
  UPDATE public.production_wo_assignments SET product_code=p_code,product_name=p_name
  WHERE id=p_assignment_id AND public.wo_normalize(wo_ref)=public.wo_normalize(p_ref);
  IF NOT FOUND THEN RAISE EXCEPTION 'Assignment tidak tersedia'; END IF;
  v_assignment_id:=p_assignment_id;
 ELSE
  -- Same normal assignment helper and OPEN transition as WO Attention PARALLEL.
  v_assignment_id:=public.create_wo_assignment(p_ref,btrim(p_line),p_code,p_name,p_date,p_shift::smallint,NULL);
  IF p_include_history AND (v_preview->>'candidate_count')::bigint>0 THEN
   v_date:=(v_preview->>'first_date')::date; v_shift:=(v_preview->>'first_shift')::integer;
   v_end_date:=CASE WHEN p_shift=1 THEN p_date-1 ELSE p_date END;
   v_end_shift:=CASE WHEN p_shift=1 THEN 3 ELSE p_shift-1 END;
   INSERT INTO public.production_wo_assignments(wo_ref,line_code,product_code,product_name,effective_date,effective_shift,ended_date,ended_shift)
    VALUES(btrim(p_ref),btrim(p_line),p_code,p_name,v_date,v_shift,v_end_date,v_end_shift) RETURNING id INTO v_historical_id;
   -- Record the explicit repair segment for both ordinary and child WOs;
   -- normal progress remains unchanged, while the guard prevents future claims.
   INSERT INTO public.production_wo_history_links(wo_ref,assignment_id,line_code,product_code,product_name,effective_date,effective_shift,ended_date,ended_shift)
    VALUES(btrim(p_ref),v_historical_id,btrim(p_line),p_code,p_name,v_date,v_shift,v_end_date,v_end_shift);
  END IF;
  INSERT INTO public.production_wo_status(wo_ref,status,updated_at) VALUES(btrim(p_ref),'OPEN',now())
   ON CONFLICT ((public.wo_normalize(wo_ref))) DO UPDATE SET status='OPEN',updated_at=now(),closed_at=NULL,closed_reason=NULL,remaining_at_close=NULL;
 END IF;
 INSERT INTO public.production_wo_actions(wo_ref,action,previous_status,new_status,assignment_id,note)
 VALUES(btrim(p_ref),CASE WHEN p_mode='CORRECT' THEN 'CORRECT_ASSIGNMENT_PRODUCT' WHEN p_include_history AND v_historical_id IS NOT NULL THEN 'ADD_PARALLEL_WITH_HISTORY' ELSE 'PARALLEL' END,
  v_status,CASE WHEN p_mode='PARALLEL' THEN 'OPEN' ELSE v_status END,v_assignment_id,
  (v_preview || jsonb_build_object('normal_assignment_id',v_assignment_id,'historical_assignment_id',v_historical_id,'admin_note',p_note))::text);
 RETURN v_preview || jsonb_build_object('normal_assignment_id',v_assignment_id,'historical_assignment_id',v_historical_id);
END $$;
REVOKE ALL ON FUNCTION public.wo_repair_preview(text,text,bigint,text,text,text,date,integer,boolean), public.wo_repair_apply(text,text,bigint,text,text,text,date,integer,boolean,jsonb,text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.wo_repair_preview(text,text,bigint,text,text,text,date,integer,boolean), public.wo_repair_apply(text,text,bigint,text,text,text,date,integer,boolean,jsonb,text) TO anon, authenticated;

-- Keep Attention Performance V2 set-based, with the same approved-link rule.
CREATE OR REPLACE FUNCTION public.wo_attention_list()
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER AS $$
WITH
refs AS MATERIALIZED (
 SELECT m.wo_ref,m.wo_qty AS qty,m.wo_start_date AS start_date,
        public.wo_normalize(m.wo_ref) AS ref_key
 FROM public.wo_list_metadata() m
),
-- The SECURITY DEFINER reader already mediates continuation access; invoke it
-- once per reference, retaining the existing INVOKER/RLS contract for logs.
continuation AS MATERIALIZED (
 SELECT r.ref_key,
        max(c.parent_wo_ref) FILTER (WHERE public.wo_normalize(c.child_wo_ref)=r.ref_key) AS parent_ref,
        max(c.child_wo_ref) FILTER (WHERE public.wo_normalize(c.parent_wo_ref)=r.ref_key) AS child_ref,
        coalesce(max(c.carryover_qty) FILTER (WHERE public.wo_normalize(c.child_wo_ref)=r.ref_key),0) AS carryover_qty,
        bool_or(public.wo_normalize(c.child_wo_ref)=r.ref_key) AS is_continuation
 FROM refs r LEFT JOIN LATERAL public.wo_continuation_read(r.wo_ref) c ON true
 GROUP BY r.ref_key
),
all_assignments AS MATERIALIZED (
 SELECT r.ref_key, a.id, a.line_code, a.product_code, a.product_name,
        a.effective_date,a.effective_shift,a.ended_date,a.ended_shift,
        public.wo_normalize(a.line_code) AS line_key,
        public.wo_normalize(a.product_code) AS code_key,
        public.wo_normalize(a.product_name) AS name_key
 FROM refs r JOIN public.production_wo_assignments a
   ON public.wo_normalize(a.wo_ref)=r.ref_key
),
active_assignments AS MATERIALIZED (
 SELECT * FROM all_assignments WHERE ended_date IS NULL
),
relevant_lines AS MATERIALIZED (
 SELECT DISTINCT line_key FROM all_assignments
),
-- Read matching lines once; no full logs are transferred to the browser.
line_logs AS MATERIALIZED (
 SELECT l.id,l.tanggal,l.shift,l.line,l.kode,l.nama,l.okpcs,l.wo_ref,
        public.wo_normalize(l.line) AS line_key,
        public.wo_normalize(l.kode) AS code_key,
        public.wo_normalize(l.nama) AS name_key,
        public.wo_normalize(l.wo_ref) AS ref_key,
        (to_jsonb(l)->>'created_at') AS created_sort
 FROM public.logs l JOIN relevant_lines r
   ON public.wo_normalize(l.line)=r.line_key
),
-- EXISTS in wo_progress counts a log once even if assignments overlap.
progress_matches AS MATERIALIZED (
 SELECT DISTINCT a.ref_key,l.id,l.okpcs
 FROM all_assignments a
 JOIN line_logs l ON l.line_key=a.line_key AND l.code_key=a.code_key AND l.name_key=a.name_key
 JOIN continuation c ON c.ref_key=a.ref_key
 WHERE (l.ref_key=a.ref_key OR (l.ref_key='' AND (NOT coalesce(c.is_continuation,false) OR public.wo_history_link_covers(a.ref_key,a.id,l.line,l.kode,l.nama,l.tanggal::date,l.shift::integer))))
   AND (l.tanggal::date,l.shift::integer)>=(a.effective_date,a.effective_shift)
   AND (a.ended_date IS NULL OR (l.tanggal::date,l.shift::integer)<=(a.ended_date,a.ended_shift))
),
progress AS MATERIALIZED (
 SELECT ref_key,coalesce(sum(coalesce(okpcs,0)),0) AS production_ok
 FROM progress_matches GROUP BY ref_key
),
-- Resolve each assignment against its applicable line logs in one set.  The
-- boundary remains in the join so NULL date/shift ordering matches the old RPC.
latest_assignment AS MATERIALIZED (
 SELECT DISTINCT ON (a.id) a.id AS assignment_id,l.tanggal,l.shift,l.kode,l.nama
 FROM active_assignments a JOIN line_logs l ON l.line_key=a.line_key
 WHERE (l.tanggal::date,l.shift::integer)>=(a.effective_date,a.effective_shift)
 ORDER BY a.id,l.tanggal DESC,l.shift::integer DESC,l.created_sort DESC NULLS LAST,l.id DESC
),
-- One set-based join and DISTINCT ON replaces a lateral query per assignment.
previous_product AS MATERIALIZED (
 SELECT DISTINCT ON (a.id) a.id AS assignment_id,l.tanggal,l.shift
 FROM active_assignments a JOIN line_logs l
   ON l.line_key=a.line_key AND l.code_key=a.code_key AND l.name_key=a.name_key
 WHERE (l.ref_key='' OR l.ref_key=a.ref_key)
   AND (l.tanggal::date,l.shift::integer)>=(a.effective_date,a.effective_shift)
 ORDER BY a.id,l.tanggal DESC,l.shift::integer DESC,l.created_sort DESC NULLS LAST,l.id DESC
),
overview AS MATERIALIZED (
 SELECT r.wo_ref,r.qty,r.start_date,coalesce(s.status,'OPEN') AS status,
        s.closed_at,s.closed_reason,s.note,
        coalesce(p.production_ok,0)+c.carryover_qty AS ok,
        r.ref_key,c.parent_ref,c.child_ref,c.carryover_qty
 FROM refs r
 LEFT JOIN public.production_wo_status s ON public.wo_normalize(s.wo_ref)=r.ref_key
 JOIN continuation c ON c.ref_key=r.ref_key
 LEFT JOIN progress p ON p.ref_key=r.ref_key
),
assignment AS (
 SELECT o.wo_ref,o.qty,o.start_date,o.status,o.closed_at,o.closed_reason,o.note,o.ok,
        a.id AS assignment_id,a.line_code,a.product_code,a.product_name,a.effective_date,a.effective_shift,
        latest.tanggal AS latest_date,latest.shift AS latest_shift,latest.kode AS latest_code,latest.nama AS latest_name,
        prior.tanggal AS previous_date,prior.shift AS previous_shift,
        (latest.tanggal IS NOT NULL AND (public.wo_normalize(latest.kode)<>public.wo_normalize(a.product_code)
          OR public.wo_normalize(latest.nama)<>public.wo_normalize(a.product_name))) AS changed,
        o.ref_key
 FROM overview o JOIN active_assignments a ON a.ref_key=o.ref_key
 LEFT JOIN latest_assignment latest ON latest.assignment_id=a.id
 LEFT JOIN previous_product prior ON prior.assignment_id=a.id
),
assignment_json AS (
 SELECT ref_key,jsonb_agg(to_jsonb(a) - 'qty' - 'ok' - 'status' - 'wo_ref' - 'closed_at' - 'closed_reason' - 'note' - 'ref_key') AS assignments
 FROM assignment a GROUP BY ref_key
),
items AS (
 SELECT jsonb_build_object('wo_ref',o.wo_ref,'qty',o.qty,'ok',o.ok,'remaining',o.qty-o.ok,'status',o.status,
   'closed_at',o.closed_at,'reason',o.closed_reason,'note',o.note,'parent_ref',o.parent_ref,'child_ref',o.child_ref,
   'carryover_qty',o.carryover_qty,'assignments',coalesce(a.assignments,'[]'::jsonb)) AS item
 FROM overview o LEFT JOIN assignment_json a ON a.ref_key=o.ref_key
)
SELECT coalesce(jsonb_agg(item),'[]'::jsonb) FROM items
$$;


REVOKE ALL ON FUNCTION public.wo_blank_owned_by_other(text,text,text,text,date,integer), public.wo_history_link_covers(text,bigint,text,text,text,date,integer), public.wo_guard_history_link_assignment() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.wo_history_link_covers(text,bigint,text,text,text,date,integer), public.wo_progress(text,text,jsonb,bigint), public.wo_attention_list() TO anon, authenticated;
