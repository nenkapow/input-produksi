-- Explicit WO / machine / product assignments. Existing logs are untouched.
CREATE TABLE IF NOT EXISTS public.production_wo_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wo_ref text NOT NULL,
    line_code text NOT NULL,
    product_code text NOT NULL,
    product_name text NOT NULL,
    effective_date date NOT NULL,
    effective_shift smallint NOT NULL CHECK (effective_shift BETWEEN 1 AND 3),
    ended_date date,
    ended_shift smallint CHECK (ended_shift BETWEEN 1 AND 3),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((ended_date IS NULL AND ended_shift IS NULL) OR
           (ended_date IS NOT NULL AND ended_shift IS NOT NULL AND
            (ended_date, ended_shift) >= (effective_date, effective_shift)))
);
CREATE INDEX IF NOT EXISTS production_wo_assignments_ref_idx ON public.production_wo_assignments (upper(trim(wo_ref)));
CREATE INDEX IF NOT EXISTS production_wo_assignments_lookup_idx ON public.production_wo_assignments (line_code, product_code, product_name, effective_date, effective_shift);
CREATE INDEX IF NOT EXISTS logs_wo_ref_idx ON public.logs (upper(trim(wo_ref)));
